public class Arithmetic_2
{
    public static void main(String args [])
    {
        byte a = 5 ;
        short b = 10 ;
        int c = a + b ;

        float d = 35.5f ;
        long e = 1008l ;
        float f = d * e ;

        double g = 20.20d ;
        double h = d - g ;

        System.out.println(c);
        System.out.println(f);
        System.out.println(h);
        System.out.println(10 + 10 / 2);
        System.out.println((10 + 10) / 2);
        System.out.println(10 / 2 * 5);
        System.out.println(10 / (2 * 5));

    }
}
